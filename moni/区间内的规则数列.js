/**
 有一个连续的数列，它的前7个数为1,2,3,4,5,6,7。从第8个数开始，每个数的值等于它所在位置前面最近连续7个数中，最大的两个数之和减去最小的两个数之和。
例如：第8个数的值，是它前面的7个数（1,2,3,4,5,6,7) 中，最大的两个数(6、7)之和减去最小的两个数（1、2)之和，即6+7— 1—2= 10。
现在给定一个位置n，请返回该位置上的数值。
 */

function getResult(n) {
    const nums = [0, 1, 2, 3, 4, 5, 6, 7];  // 索引0占位，1-7为初始值
    
    for (let i = 8; i <= n; i++) {
        // 取前7个数，排序
        const window = nums.slice(i - 7, i).sort((a, b) => a - b);
        // 最大两个之和 - 最小两个之和
        nums[i] = window[5] + window[6] - window[0] - window[1];
    }
    
    return nums[n];
}