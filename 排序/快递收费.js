/**
 题目内容
请开发一个快递驿站计费系统，根据给定的一组快递存取记录，系统计费每位业主要缴纳的总费用，并按总费用从高到低输出。系统计费规则如下:
1. 免费存放时间为12小时，从存件时间开始计时，总存放时间≤12小时不收费，存放时间=取件时间一存件时间;
2. 超出免费存放时间的，每12小时收取1元，不足12小时按12小时计算，比如存放了25个小时，超出免费时间13小时，需要收费2元;3.同一个房间号的业主，可能有多条存取记录，需要将业主所有快递的超时费用累加得到总费用。
输入描述
一组快递存取记录列表，其中一条存取记录对应一个数组，该数组包含3个非负整数字段:存件时间、取件时间和业主房间号;存取时间已简化处理采用整型数字，非24小时制格式;
1. 0 <= 存件时间 <= 取件时间 <= 100000
2. 100 < 房间号 < 10000
3. 输入记录条数范围 1 <= N <= 1000
输出描述
一个二维数组Q/列表，表述一组收费记录，每一条收费记录对应一个数组，该数组包含2个整数字段:业主房间号和总费用;收费按总费用从高到低排序，总费用相同的，按房间号从小到大排序;
 */

function solve(records) {
    const costMap = new Map();
    
    for (const [start, end, room] of records) {
        const extra = end - start - 12;
        const cost = extra > 0 ? Math.ceil(extra / 12) : 0;
        costMap.set(room, (costMap.get(room) || 0) + cost);
    }
    
    return [...costMap]
        .sort((a, b) => b[1] - a[1] || a[0] - b[0])
        .map(([room, cost]) => [room, cost]);
}