/**
 题目内容
给定一个非负整数数组 nums 和—个目标进制 base(2 <= base <= 16)，请完成以下操作并返回最终结果：
1. 进制转换：将数组中每个整数转换为 base 进制的字符串(小写字母表示 10-15 如 10→"a"，15→"f")；
2. 自定义排序：对转换后的字符串数组按字符串对应的十进制数值降序排列;
3. 注意：0转换为任意进制的结果均为“0”；输入的整数均为非负整数。
补充说明
• 1 <= nums.length <= 100
• 0 <= nums[i] <= 106
• 2 <= base <= 16
输入
第一行输入nums数组，使用，进行分割
第二行输入目标base
输出
输出排序后的字符串Q数组，使用，进行分割
 */

function convertNumAndSort(nums, base) {
    // 按数值降序排序，然后转换为base进制字符串
    return nums
        .sort((a, b) => b - a)
        .map(num => num.toString(base));
}