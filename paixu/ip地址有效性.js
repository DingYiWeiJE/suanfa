/**
 题目内容
企业内网运维中，需要对分配的IP地址段进行有效性校验：给定一个存储Q内网IP地址列表，要求筛选出符合A类Q内网网段（10.0.0.0-10.255.255.255)的IP地址，并按“网段层级”(即IP的第二个分段数值/第三分段/第四分段)升序排序。
A类内网IP规则:
1.IP格式为xxx.xxx.xxx.xxx(4个分段，每个分段为0-255的整数)；
2. 第一个分段必须是10;
3. 每个分段不能以0开头(除非分段本身是0，如10.0.1.1 合法，10.01.1.1 不合法)。
补充说明:给定的每组IP地址列表中最多有15个IP地址；输入IP格式不保证合法。
输入描述
以，分割输入所有IP地址
输出描述
以，输出所有合法地址，并按“网段层级”(即IP的第二个分段数值/第三分段/第四分段)升序排序。
 */

function getValidIP(ips) {
    const isValidPart = p => /^(0|[1-9]\d{0,2})$/.test(p) && +p <= 255;
    
    return ips
        .filter(ip => {
            const parts = ip.split(".");
            return parts.length === 4 && parts[0] === "10" && parts.every(isValidPart);
        })
        .map(ip => ip.split(".").map(Number))
        .sort((a, b) => a[1] - b[1] || a[2] - b[2] || a[3] - b[3])
        .map(arr => arr.join("."));
}

/**
这道题的巧妙之处是， 先用正则表达式来筛选， 然后再用数值大小来过滤
注意， （情况1 | 情况2） 
\d 表示数字
{0，2} 表示0个或者2个
? 表示0个或者1个
*表示0个或者n个
+ 表示1个或者n个
 */