/**
 题目内容
给定一个非负整数数组 nums，满足以下两个前提条件：
1. 数组长度为偶数，且 2 ≤ nums.length ≤ 20000
2. 数组中恰好有一半元素是偶数，另一半元素是奇数
请你对该数组进行重构，满足以下两个核心要求：
3. 重构后的数组中，所有位于偶数下标（下标从0开始）的元素必须是偶数，所有位于奇数下标的元素必须是奇数
4.重构后，所有占据偶数下标的偶数元素，需按照从小到大的升序排列；所有占据奇数下标的奇数元素，也需按照从小到大的升序排列返回满足上述所有条件的重构后数组。
补充说明
1. 数组长度 n 满足 2 ≤ n ≤ 20000，且 n%2 == 0
2. 数组中的元素为非负整数，满足 0 ≤ nums[i] ≤ 1000
3. 数组中偶数和奇数的数量严格相等，各占 n/2个
4. 满足条件的输出数组是唯一的
 */

function sortArr(nums) {
    const evens = nums.filter(n => n % 2 === 0).sort((a, b) => a - b);
    const odds = nums.filter(n => n % 2 === 1).sort((a, b) => a - b);
    
    const result = [];
    for (let i = 0; i < evens.length; i++) {
        result.push(evens[i], odds[i]);
    }
    return result;
}