/**
 题目内容
给定电动车的电池容量 capacity（kwh）、能耗效率 efficiency（kwh/100km）、驾驶场景(城市/高速/山路，int类Q型，分别是0/1/2），计算该车的有效续航里程（km）。
核心公式：理论续航里程= (电池容量*容量能耗修正系数)/能耗效率*100；(结果按四舍五入保留4 位小数)
有效续航里程= 理论续航里程*总体损耗系数，相关系数计算规则如下:
容量能耗修正数Kp：不同容量下，能效效率不同，分段进行能效效率修正
• 零段：电池容量 capacity>=160kWh 时， kp0 = 1(无损耗)
• 一段：电池容量 160kWh>capacity>80kWh 时， kp1 = 0.98
• 二段：电池容量 capacity<=80kwh 时， kp2 = 0.95
总体损耗系数 kd：基础损耗系数为 kb (0.956)*场景修正系数 kc (结果按四舍五入保留4 位小数)
补充约束:
1. 电池容量范围：20 ≤ capacity ≤ 200 (非整数需向下取整);
2. 标准能耗效率范围： 5 ≤ efficiency ≤ 30;
3.驾驶场景仅支持：“city”(城市) 0/场景修正系数kc0= 1、“highway”(高速)1/场景修正系数kc1 = 0.92、“mountain”(山路)2 /场景修正系数 kc2 = 0.85;
4. 结果要求：有效续航里程需四舍五入为整数，输出里程km。
输入描述
输入为一行，包含三个值：电池容量（可能含小数)、能耗效率（可能含小数）、驾驶场景（整数0/1/2），以逗号分隔。
输出描述
输出一个整数，表示四舍五入后的有效续航里程（单位：km）。
 */

function solve(capacity, efficiency, type) {
    const cap = Math.floor(capacity);
    
    // 分段累加容量能耗修正系数
    const coefficient = 
        Math.min(cap, 80) * 0.95 +
        Math.max(0, Math.min(cap, 160) - 80) * 0.98 +
        Math.max(0, cap - 160);
    
    // 总体损耗系数
    const kd = 0.956 * [1, 0.92, 0.85][type];
    
    // 理论续航 × 总体损耗系数
    return Math.round(coefficient / efficiency * 100 * kd);
}

